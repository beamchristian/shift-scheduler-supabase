-- Shift Scheduler schema for Supabase (Postgres).
-- Run once: Supabase dashboard > SQL Editor > New query > paste this > Run.

create table if not exists settings (
  id integer primary key,
  earliest_start text default '06:00',
  latest_start text default '12:00',
  payroll_pct double precision default 15,
  weekly_sales double precision default 38000,
  fill_extra double precision default 1,
  rate_override double precision default 21.15,
  max_closes double precision default 3,
  break_minutes double precision default 30,
  break_after double precision default 5,
  breaks_unpaid double precision default 1,
  count_paid_hours double precision default 0,
  schedule_title text default 'Weekly Schedule'
);

create table if not exists store_hours (
  id integer generated by default as identity primary key,
  day integer not null,
  "open" text default '06:00',
  "close" text default '20:00',
  sales_pct double precision default 16.67
);

create table if not exists employees (
  id integer generated by default as identity primary key,
  name text,
  position text,
  type text default 'PT',
  min_hours double precision,
  max_hours double precision,
  skills text default '',
  shifts text default '',
  max_closes double precision,
  avail_1 text default '',
  avail_2 text default '',
  avail_3 text default '',
  avail_4 text default '',
  avail_5 text default '',
  avail_6 text default ''
);

create table if not exists shift_templates (
  id integer generated by default as identity primary key,
  name text,
  day integer not null,
  "start" text,
  "end" text,
  needed integer default 1,
  skill text default '',
  only_for text default ''
);

create table if not exists schedule (
  id integer generated by default as identity primary key,
  day integer,
  template_id integer,
  employee_id integer,
  name text,
  "start" text,
  "end" text
);

-- Starting rows (the app also creates these if they are missing)
insert into settings (id) values (1) on conflict (id) do nothing;
insert into store_hours (day, "open", "close", sales_pct)
select d, '06:00', '20:00', w
from (values (1, 19.0), (2, 15.5), (3, 14.0), (4, 15.0), (5, 17.0), (6, 19.5)) as v(d, w)
where not exists (select 1 from store_hours);

-- Lock the tables against Supabase's public API. The app connects directly from the server with the
-- database connection string, which is not affected by row level security. With no policies, the
-- public anon key cannot read or change anything here.
alter table settings enable row level security;
alter table store_hours enable row level security;
alter table employees enable row level security;
alter table shift_templates enable row level security;
alter table schedule enable row level security;
