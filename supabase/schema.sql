-- Shift Scheduler: complete setup for a NEW Supabase project.
-- Run once: Supabase dashboard > SQL Editor > New query > paste this > Run.
--
-- This gives the same result as running migrations 002 to 007 in order on the original schema.
-- Do not run it on a project that already has the tables. For an existing project, run only the
-- migrations you have not run yet.

-- Stores. Each store has its own departments.
create table if not exists stores (
  id integer generated by default as identity primary key,
  name text not null,
  -- Store-wide payroll target as a percent of sales. Blank means none is set.
  target_payroll_pct double precision,
  created_at timestamptz default now()
);

-- Store managers. A store manager can manage every department in their store.
create table if not exists store_members (
  id integer generated by default as identity primary key,
  store_id integer not null references stores(id) on delete cascade,
  email text not null,
  created_at timestamptz default now(),
  unique (store_id, email)
);

-- People who can see and create every store.
create table if not exists app_admins (
  email text primary key
);

-- Departments. Each department is its own workspace with its own data, and belongs to one store.
create table if not exists departments (
  id integer generated by default as identity primary key,
  store_id integer not null references stores(id),
  name text not null,
  created_at timestamptz default now()
);
create unique index if not exists departments_store_name_idx on departments (store_id, lower(name));

-- Department managers: who may work in each department. Admins and store managers manage this list.
create table if not exists department_members (
  id integer generated by default as identity primary key,
  department_id integer not null references departments(id) on delete cascade,
  email text not null,
  role text not null check (role in ('manager')),
  created_at timestamptz default now(),
  unique (department_id, email)
);

-- Record of changes made in the app.
create table if not exists audit_log (
  id integer generated by default as identity primary key,
  department_id integer references departments(id) on delete cascade,
  email text,
  action text not null,
  detail text,
  created_at timestamptz default now()
);

-- Payroll, store and break settings. One row per department.
create table if not exists settings (
  id integer generated by default as identity primary key,
  department_id integer references departments(id),
  earliest_start text default '06:00',
  latest_start text default '12:00',
  payroll_pct double precision default 15,
  weekly_sales double precision default 38000,
  fill_extra double precision default 1,
  rate_override double precision default 21.15,
  max_closes double precision default 3,
  break_minutes double precision default 30,
  break_after double precision default 5,
  breaks_unpaid double precision default 1,
  count_paid_hours double precision default 0,
  schedule_title text default 'Weekly Schedule'
);

-- Opening and closing times and the share of the week's sales for each day.
create table if not exists store_hours (
  id integer generated by default as identity primary key,
  department_id integer references departments(id) default 1,
  day integer not null,
  "open" text default '06:00',
  "close" text default '20:00',
  sales_pct double precision default 16.67
);

create table if not exists employees (
  id integer generated by default as identity primary key,
  department_id integer references departments(id) default 1,
  name text,
  position text,
  type text default 'PT',
  min_hours double precision,
  max_hours double precision,
  skills text default '',
  shifts text default '',
  max_closes double precision,
  avail_1 text default '',
  avail_2 text default '',
  avail_3 text default '',
  avail_4 text default '',
  avail_5 text default '',
  avail_6 text default ''
);

create table if not exists shift_templates (
  id integer generated by default as identity primary key,
  department_id integer references departments(id) default 1,
  name text,
  day integer not null,
  "start" text,
  "end" text,
  needed integer default 1,
  skill text default '',
  only_for text default ''
);

create table if not exists schedule (
  id integer generated by default as identity primary key,
  department_id integer references departments(id) default 1,
  day integer,
  template_id integer,
  employee_id integer,
  name text,
  "start" text,
  "end" text
);

-- Indexes for the per-department lookups the app makes on every request.
create index if not exists settings_department_idx on settings (department_id);
create index if not exists store_hours_department_idx on store_hours (department_id);
create index if not exists employees_department_idx on employees (department_id);
create index if not exists shift_templates_department_idx on shift_templates (department_id);
create index if not exists schedule_department_idx on schedule (department_id);

-- The first store, and the seven departments in it. Deli is first, so it gets id 1.
insert into stores (id, name) values (1, 'Store 1') on conflict do nothing;
select setval(pg_get_serial_sequence('stores', 'id'), (select max(id) from stores));
insert into departments (id, store_id, name) values
  (1, 1, 'Deli'), (2, 1, 'Seafood'), (3, 1, 'Grocery'), (4, 1, 'Bakery'), (5, 1, 'Butcher'), (6, 1, 'Cafe'), (7, 1, 'Produce')
on conflict do nothing;
select setval(pg_get_serial_sequence('departments', 'id'), (select max(id) from departments));

-- Every department gets a settings row and six store-hours rows (Monday to Saturday).
insert into settings (department_id, schedule_title)
select department.id, department.name || ' Weekly Schedule'
from departments department
where not exists (select 1 from settings existing where existing.department_id = department.id);

insert into store_hours (department_id, day, "open", "close", sales_pct)
select department.id, defaults.day_number, '06:00', '20:00', defaults.sales_pct
from departments department
cross join (values (1, 19.0), (2, 15.5), (3, 14.0), (4, 15.0), (5, 17.0), (6, 19.5))
  as defaults(day_number, sales_pct)
where not exists (select 1 from store_hours existing where existing.department_id = department.id);

