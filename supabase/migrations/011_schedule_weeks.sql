-- Gives every schedule a week. Each department can have one schedule per week (Monday to Saturday),
-- marked Draft or Published. Existing schedules move into the week of Monday 2 November 2026 as Published.

-- One row per department per week. week_start is always a Monday.
-- The numbers (forecast, payroll %, rate, day weights) are the week's own. A published week keeps the
-- numbers it was published with, so changing Settings later does not change it.
create table if not exists schedule_weeks (
  id integer generated by default as identity primary key,
  department_id integer not null references departments(id) on delete cascade,
  week_start date not null check (extract(isodow from week_start) = 1),
  status text not null default 'draft' check (status in ('draft', 'published')),
  -- This week's sales forecast. Blank means it has not been entered yet.
  weekly_sales double precision,
  -- Saved when the week is published, and used while it stays published.
  payroll_pct double precision,
  rate_override double precision,
  -- Day weights keyed by day number, for example {"1": 31, "2": 23}.
  day_weights jsonb,
  generated_by text,
  generated_at timestamptz,
  published_by text,
  published_at timestamptz,
  created_at timestamptz default now(),
  unique (department_id, week_start)
);

alter table schedule_weeks enable row level security;

-- Each scheduled shift belongs to one week. Deleting a week deletes its shifts.
alter table schedule add column if not exists week_id integer references schedule_weeks(id) on delete cascade;
create index if not exists schedule_week_idx on schedule (week_id);

-- Existing schedules become the week of 2 November 2026, published, with each department's current numbers.
insert into schedule_weeks (department_id, week_start, status, weekly_sales, payroll_pct, rate_override,
                            day_weights, published_by, published_at)
select department.id, date '2026-11-02', 'published', settings.weekly_sales, settings.payroll_pct,
       settings.rate_override,
       (select jsonb_object_agg(hours.day::text, hours.sales_pct)
          from store_hours hours where hours.department_id = department.id),
       'migration', now()
from departments department
left join settings on settings.department_id = department.id
where exists (select 1 from schedule shift where shift.department_id = department.id)
on conflict (department_id, week_start) do nothing;

update schedule shift
set week_id = week.id
from schedule_weeks week
where week.department_id = shift.department_id
  and week.week_start = date '2026-11-02'
  and shift.week_id is null;

-- Every shift now has a week, so make it required.
alter table schedule alter column week_id set not null;
