-- Adds departments (one workspace each) and who may access them. Existing data becomes the Deli department.

create table if not exists departments (
  id integer generated by default as identity primary key,
  name text not null,
  created_at timestamptz default now()
);

create table if not exists department_members (
  id integer generated by default as identity primary key,
  department_id integer not null references departments(id) on delete cascade,
  email text not null,
  role text not null check (role in ('owner', 'manager')),
  created_at timestamptz default now(),
  unique (department_id, email)
);

create table if not exists audit_log (
  id integer generated by default as identity primary key,
  department_id integer references departments(id) on delete cascade,
  email text,
  action text not null,
  detail text,
  created_at timestamptz default now()
);

-- The seven departments. Deli keeps the data you already have.
insert into departments (id, name) values (1, 'Deli') on conflict do nothing;
insert into departments (name) values ('Seafood'), ('Grocery'), ('Bakery'), ('Butcher'), ('Cafe'), ('Produce');
select setval(pg_get_serial_sequence('departments', 'id'), (select max(id) from departments));

-- Every department gets its own settings row and store hours. Its schedule starts empty.
alter table settings add column if not exists department_id integer references departments(id);
update settings set department_id = 1 where department_id is null;
insert into settings (department_id, earliest_start, latest_start, payroll_pct, weekly_sales, fill_extra, rate_override, max_closes, break_minutes, break_after, breaks_unpaid, count_paid_hours, schedule_title)
select d.id, s.earliest_start, s.latest_start, s.payroll_pct, s.weekly_sales, s.fill_extra, s.rate_override, s.max_closes, s.break_minutes, s.break_after, s.breaks_unpaid, s.count_paid_hours, d.name || ' Weekly Schedule'
from departments d cross join (select * from settings where department_id = 1 limit 1) s
where d.id <> 1 and not exists (select 1 from settings x where x.department_id = d.id);

alter table store_hours add column if not exists department_id integer references departments(id);
update store_hours set department_id = 1 where department_id is null;
insert into store_hours (department_id, day, "open", "close", sales_pct)
select d.id, h.day, h."open", h."close", h.sales_pct
from departments d cross join store_hours h
where h.department_id = 1 and d.id <> 1 and not exists (select 1 from store_hours x where x.department_id = d.id);

alter table employees add column if not exists department_id integer references departments(id);
update employees set department_id = 1 where department_id is null;
alter table shift_templates add column if not exists department_id integer references departments(id);
update shift_templates set department_id = 1 where department_id is null;
alter table schedule add column if not exists department_id integer references departments(id);
update schedule set department_id = 1 where department_id is null;

-- You are the first owner of every department.
