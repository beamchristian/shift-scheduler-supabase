-- Adds stores. Every department belongs to one store. Store owners and managers get every department in
-- their store, and company admins can see every store. Everything that exists today moves into Store 1.

-- Stores, and the store managers for each one.
-- Store managers are owners of every department in their store.
create table if not exists stores (
  id integer generated by default as identity primary key,
  name text not null,
  created_at timestamptz default now()
);

create table if not exists store_members (
  id integer generated by default as identity primary key,
  store_id integer not null references stores(id) on delete cascade,
  email text not null,
  created_at timestamptz default now(),
  unique (store_id, email)
);

-- People who can see and create every store.
create table if not exists app_admins (
  email text primary key
);

-- Store 1 holds everything that exists today. Rename it with an update to stores if you like.
insert into stores (id, name) values (1, 'Store 1') on conflict do nothing;
select setval(pg_get_serial_sequence('stores', 'id'), (select max(id) from stores));

-- Every department belongs to a store.
alter table departments add column if not exists store_id integer references stores(id);
update departments set store_id = 1 where store_id is null;
alter table departments alter column store_id set not null;

-- Department names only need to be unique within a store, so each store can have its own Deli.
create unique index if not exists departments_store_name_idx on departments (store_id, lower(name));

