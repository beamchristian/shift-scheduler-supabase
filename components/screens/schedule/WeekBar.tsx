"use client";
import type { ScheduleWeek } from "../../../lib/types";
import { formatTimestamp } from "../../../lib/ui/format";
import { cardClass, fieldClass, secondaryButtonClass } from "../../../lib/ui/styles";
import { addDays, isPastWeek, weekLabel } from "../../../lib/weeks";
import type { WeekListing } from "../../types";

// Colors for the small status labels.
const PILL_CLASSES = {
  published: "bg-emerald-50 text-emerald-800 ring-emerald-200",
  draft: "bg-amber-50 text-amber-800 ring-amber-200",
  empty: "bg-slate-100 text-slate-600 ring-slate-200",
  past: "bg-slate-100 text-slate-600 ring-slate-200",
  here: "bg-indigo-50 text-indigo-700 ring-indigo-200",
};

// A small rounded label, such as "Published" or "This week". The store overview uses it too.
export function Pill({ tone, children }: { tone: keyof typeof PILL_CLASSES; children: string }) {
  return (
    <span className={`inline-flex items-center rounded-full px-2.5 py-0.5 text-xs font-semibold ring-1 ring-inset ${PILL_CLASSES[tone]}`}>
      {children}
    </span>
  );
}

// The status label for the week: Published, Draft, or No schedule yet.
function StatusPill({ week, hasShifts }: { week: ScheduleWeek; hasShifts: boolean }) {
  if (week.status === "published") return <Pill tone='published'>Published</Pill>;
  if (!hasShifts) return <Pill tone='empty'>No schedule yet</Pill>;
  return <Pill tone='draft'>Draft</Pill>;
}

// The line under the week name: who generated and published it, and when.
function HistoryLine({ week, hasShifts }: { week: ScheduleWeek; hasShifts: boolean }) {
  const parts: string[] = [];
  if (week.generated_at) parts.push(`Generated by ${week.generated_by ?? "someone"} on ${formatTimestamp(week.generated_at)}`);
  else if (hasShifts) parts.push("Generated before weeks were tracked");
  if (week.status === "published" && week.published_at && week.published_by !== "migration")
    parts.push(`Published by ${week.published_by ?? "someone"} on ${formatTimestamp(week.published_at)}`);
  if (!parts.length) return null;
  return <p className='text-xs text-slate-500'>{parts.join(" · ")}</p>;
}

// The text for one choice in the saved-weeks list, for example "Nov 2 – 7, 2026 · Published · 36 shifts".
function weekOptionLabel(listing: WeekListing): string {
  const statusText = listing.status === "published" ? "Published" : listing.shift_count ? "Draft" : "Empty";
  return `${weekLabel(listing.week_start)} · ${statusText} · ${listing.shift_count} shift${listing.shift_count === 1 ? "" : "s"}`;
}

// The Publish button for a draft with shifts, or the Unpublish button for a published week.
// Nothing shows for a week with no schedule, since there is nothing to publish yet.
function PublishButton({
  week,
  hasShifts,
  isChangingStatus,
  onPublish,
  onUnpublish,
}: {
  week: ScheduleWeek;
  hasShifts: boolean;
  isChangingStatus: boolean;
  onPublish: () => void;
  onUnpublish: () => void;
}) {
  if (week.status === "published")
    return (
      <button className={secondaryButtonClass} onClick={onUnpublish} disabled={isChangingStatus}>
        {isChangingStatus ? "Unpublishing…" : "Unpublish"}
      </button>
    );
  if (!hasShifts) return null;
  return (
    <button
      className='inline-flex items-center justify-center rounded-lg bg-emerald-600 px-4 py-2.5 text-sm font-semibold text-white shadow-sm transition hover:bg-emerald-700 disabled:opacity-60'
      onClick={onPublish}
      disabled={isChangingStatus}
    >
      {isChangingStatus ? "Publishing…" : "Publish schedule"}
    </button>
  );
}

// The bar at the top of the Schedule screen that picks the week: arrows for the week before and after,
// buttons for this week and next week, and a list of every week that has a saved schedule.
// It also shows the week's status (Published, Draft, Past), who generated and published it,
// and the button to publish or unpublish it.
export function WeekBar({
  week,
  hasShifts,
  savedWeeks,
  today,
  currentWeek,
  upcomingWeek,
  isLoading,
  isChangingStatus,
  onChangeWeek,
  onPublish,
  onUnpublish,
}: {
  week: ScheduleWeek;
  hasShifts: boolean;
  savedWeeks: WeekListing[];
  // Today's date and the two weeks around it, in the store's time zone, as "YYYY-MM-DD".
  today: string;
  currentWeek: string;
  upcomingWeek: string;
  // True while a different week is loading.
  isLoading: boolean;
  // True while the week is being published or unpublished.
  isChangingStatus: boolean;
  onChangeWeek: (weekStart: string) => void;
  onPublish: () => void;
  onUnpublish: () => void;
}) {
  const weekStart = week.week_start;
  // The list always includes the week on screen, even when nothing is saved for it yet.
  const listedWeeks = savedWeeks.some((listing) => listing.week_start === weekStart)
    ? savedWeeks
    : [...savedWeeks, { week_start: weekStart, status: week.status, shift_count: 0 }].sort((first, second) =>
        second.week_start.localeCompare(first.week_start),
      );
  const arrowClass =
    "flex h-9 w-9 shrink-0 items-center justify-center rounded-lg border border-slate-300 bg-white text-slate-700 shadow-sm hover:bg-slate-50";
  const jumpClass =
    "rounded-lg px-3 py-1.5 text-sm font-medium text-indigo-700 hover:bg-indigo-50 disabled:cursor-default disabled:text-slate-400 disabled:hover:bg-transparent";

  return (
    <div className={`${cardClass} mb-4 p-4`}>
      <div className='flex flex-col gap-3 lg:flex-row lg:items-center lg:justify-between'>
        <div className='flex flex-col gap-2 sm:flex-row sm:items-center'>
          {/* On a phone the arrows sit at the two ends with the week name between them. */}
          <div className='flex items-center justify-between gap-2 sm:justify-start'>
            <button className={arrowClass} aria-label='Week before' onClick={() => onChangeWeek(addDays(weekStart, -7))}>
              ◀
            </button>
            <div className='min-w-0 px-1 text-center sm:text-left'>
              <div className='text-xs font-medium uppercase tracking-wide text-slate-500'>Week of</div>
              <div className={`whitespace-nowrap text-lg font-semibold text-slate-900 ${isLoading ? "opacity-50" : ""}`}>
                {weekLabel(weekStart)}
              </div>
            </div>
            <button className={arrowClass} aria-label='Week after' onClick={() => onChangeWeek(addDays(weekStart, 7))}>
              ▶
            </button>
          </div>
          <div className='flex flex-wrap items-center justify-center gap-1.5 sm:ml-1 sm:justify-start'>
            <StatusPill week={week} hasShifts={hasShifts} />
            {weekStart === currentWeek && <Pill tone='here'>This week</Pill>}
            {weekStart === upcomingWeek && weekStart !== currentWeek && <Pill tone='here'>Next week</Pill>}
            {isPastWeek(weekStart, today) && <Pill tone='past'>Past week</Pill>}
          </div>
        </div>

        <div className='flex flex-wrap items-center gap-1'>
          <button className={jumpClass} disabled={weekStart === currentWeek} onClick={() => onChangeWeek(currentWeek)}>
            This week
          </button>
          <button className={jumpClass} disabled={weekStart === upcomingWeek} onClick={() => onChangeWeek(upcomingWeek)}>
            Next week
          </button>
          <select
            aria-label='Saved weeks'
            className={`${fieldClass} ml-1 w-auto py-1.5`}
            value={weekStart}
            onChange={(changeEvent) => onChangeWeek(changeEvent.target.value)}
          >
            {listedWeeks.map((listing) => (
              <option key={listing.week_start} value={listing.week_start}>
                {weekOptionLabel(listing)}
              </option>
            ))}
          </select>
        </div>
      </div>
      <div className='mt-3 flex flex-col gap-3 border-t border-slate-100 pt-3 sm:flex-row sm:items-center sm:justify-between'>
        <div>
          <HistoryLine week={week} hasShifts={hasShifts} />
          {week.status !== "published" && hasShifts && (
            <p className='mt-1 text-xs text-slate-500'>
              Publish when it is ready. A published schedule is locked until it is unpublished.
            </p>
          )}
        </div>
        <PublishButton
          week={week}
          hasShifts={hasShifts}
          isChangingStatus={isChangingStatus}
          onPublish={onPublish}
          onUnpublish={onUnpublish}
        />
      </div>
    </div>
  );
}
